// Generates src/abi/earnx.ts from the Foundry build output and deployment records,
// so the app's ABIs and addresses always match what is on-chain.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { keccak256 } from 'viem';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'contracts');
const abi = (name) => JSON.parse(readFileSync(join(root, 'out', `${name}.sol`, `${name}.json`), 'utf8')).abi;

const deployments = {};
for (const file of readdirSync(join(root, 'deployments'))) {
  if (!file.endsWith('.json') || file.startsWith('31337')) continue;
  const d = JSON.parse(readFileSync(join(root, 'deployments', file), 'utf8'));
  deployments[d.chainId] = {
    protocol: d.protocol,
    invoiceNFT: d.invoiceNFT,
    tokens: d.tokens,
    deployedAtBlock: d.deployedAtBlock,
  };
}

// keccak256 of each sample document, so the app can link an invoice's docsHash to its file.
const sampleDocs = {};
for (const file of readdirSync(join(root, 'demo', 'invoices'))) {
  const bytes = readFileSync(join(root, 'demo', 'invoices', file));
  sampleDocs[keccak256(bytes)] = `contracts/demo/invoices/${file}`;
}

const out = `// Generated by scripts/sync-contracts.mjs from contracts/out and contracts/deployments. Do not edit.
export const protocolAbi = ${JSON.stringify(abi('EarnXProtocol'), null, 2)} as const;

export const invoiceNftAbi = ${JSON.stringify(abi('EarnXInvoiceNFT'), null, 2)} as const;

export const deployments = ${JSON.stringify(deployments, null, 2)} as const;

export const sampleDocs: Record<string, string> = ${JSON.stringify(sampleDocs, null, 2)};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'abi', 'earnx.ts'), out);
console.log('wrote src/abi/earnx.ts for chains', Object.keys(deployments).join(', '));
