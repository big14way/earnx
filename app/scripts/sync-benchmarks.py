"""Writes src/data/benchmarks.ts from the World Bank Commodity Price Data (the "Pink Sheet").

Usage: python3 scripts/sync-benchmarks.py path/to/CMO-Historical-Data-Monthly.xlsx
Download the workbook from https://www.worldbank.org/en/research/commodity-markets (needs openpyxl).
"""
import json, sys, pathlib
import openpyxl

SERIES = {  # our key -> (Pink Sheet column name, unit in the sheet)
    'cocoa': 'Cocoa',
    'coffee_arabica': 'Coffee, Arabica',
    'coffee_robusta': 'Coffee, Robusta',
    'tea': 'Tea, avg 3 auctions',
    'tea_mombasa': 'Tea, Mombasa',
    'palm_oil': 'Palm oil',
    'groundnuts': 'Groundnuts',
    'maize': 'Maize',
    'rice': 'Rice, Thai 5%',
    'soybeans': 'Soybeans',
    'sugar': 'Sugar, world',
    'cotton': 'Cotton, A Index',
    'banana': 'Banana, Europe',
    'orange': 'Orange',
}

wb = openpyxl.load_workbook(sys.argv[1], read_only=True, data_only=True)
rows = list(wb['Monthly Prices'].iter_rows(values_only=True))
updated = next(r[0] for r in rows[:6] if r[0] and str(r[0]).startswith('Updated on'))
names, units = rows[4], rows[5]
data = [r for r in rows[6:] if r[0]]
out = {}
for key, col in SERIES.items():
    i = next(i for i, n in enumerate(names) if n and n.strip() == col)
    month, value = next((r[0], r[i]) for r in reversed(data) if isinstance(r[i], (int, float)))
    unit = units[i]
    per_tonne = value * 1000 if unit == '($/kg)' else value
    out[key] = {'name': col, 'usdPerTonne': round(per_tonne, 2), 'month': month}

ts = f"""// Generated by scripts/sync-benchmarks.py from the World Bank Pink Sheet. Do not edit.
// {updated}. Source: https://www.worldbank.org/en/research/commodity-markets
export const benchmarks = {json.dumps(out, indent=2)} as const;

export type BenchmarkKey = keyof typeof benchmarks;
export const benchmarkSource = {{ name: 'World Bank Commodity Price Data (Pink Sheet)', url: 'https://www.worldbank.org/en/research/commodity-markets', updated: {json.dumps(updated.replace('Updated on ', ''))} }};
"""
pathlib.Path(__file__).resolve().parent.parent.joinpath('src/data/benchmarks.ts').write_text(ts)
print('wrote src/data/benchmarks.ts:', ', '.join(f"{k}={v['usdPerTonne']}" for k, v in out.items()))
